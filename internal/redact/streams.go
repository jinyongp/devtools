package redact

import (
	"context"
	"errors"
	"fmt"
	"io"
	"os"
	"sync/atomic"
)

var ErrOutput = errors.New("output_protection_failed")

// Streams owns patterns until every protected stream has ended, independently
// of the vault/key-cache lifetime. Raw selection never bypasses captured logs.
type Streams struct {
	Out       io.Writer
	Err       io.Writer
	Plan      Plan
	Context   context.Context
	matcher   *Matcher
	outWriter *Writer
	errWriter *Writer
	failed    *atomic.Bool
	cancel    context.CancelFunc
	fileSinks []*fileSink
}

func (Streams) Format(s fmt.State, _ rune) { io.WriteString(s, "[REDACTED]") }
func (Streams) MarshalJSON() ([]byte, error) {
	return nil, errors.New("private output streams cannot be serialized")
}
func (Streams) MarshalText() ([]byte, error) {
	return nil, errors.New("private output streams cannot be serialized")
}

type notifyingWriter struct {
	writer *Writer
	failed *atomic.Bool
	cancel context.CancelFunc
}

func (w notifyingWriter) Write(p []byte) (int, error) {
	n, err := w.writer.Write(p)
	if err != nil && !errors.Is(err, context.Canceled) && !errors.Is(err, context.DeadlineExceeded) {
		w.failed.Store(true)
		w.cancel()
	}
	return n, err
}
func (notifyingWriter) Format(s fmt.State, _ rune) { io.WriteString(s, "[REDACTED]") }

func Protect(ctx context.Context, patterns [][]byte, plan Plan, out, diagnostic io.Writer) (*Streams, error) {
	if !plan.Valid() {
		return nil, errors.New("invalid_output_mode")
	}
	if out == nil {
		out = io.Discard
	}
	if diagnostic == nil {
		diagnostic = io.Discard
	}
	child, cancel := context.WithCancel(ctx)
	streams := &Streams{Out: out, Err: diagnostic, Plan: plan, Context: child, failed: &atomic.Bool{}, cancel: cancel}
	for _, pattern := range patterns {
		if len(pattern) > 0 && len(pattern) < 4 {
			streams.Plan.ShortSecrets = true
		}
	}
	if plan.Stdout == Raw && plan.Stderr == Raw {
		return streams, nil
	}
	matcher, err := New(patterns)
	if err != nil {
		cancel()
		return nil, err
	}

	streams.matcher = matcher
	filterFile := func(destination io.Writer, effective Mode, reason string) io.Writer {
		if _, ok := destination.(*os.File); ok && effective == Redacted && reason != "capture" {
			sink := newFileSink(child, destination, func() { streams.failed.Store(true); cancel() })
			streams.fileSinks = append(streams.fileSinks, sink)
			return sink
		}
		return destination
	}
	out = filterFile(out, plan.Stdout, plan.StdoutReason)
	diagnostic = filterFile(diagnostic, plan.Stderr, plan.StderrReason)
	// Even an empty pattern set retains the requested pipe/TTY behavior. It does
	// not promise to infer unknown secrets generated by the application itself.
	if plan.Stdout == Redacted {
		streams.outWriter = NewWriter(out, matcher)
		streams.Out = notifyingWriter{streams.outWriter, streams.failed, cancel}
	}
	if plan.Stderr == Redacted {
		streams.errWriter = NewWriter(diagnostic, matcher)
		streams.Err = notifyingWriter{streams.errWriter, streams.failed, cancel}
	}
	return streams, nil
}

// Close must follow process output completion. If the process could not obtain
// reliable EOF (cancellation/WaitDelay), drop pending bytes and let any blocked
// callbacks retain their patterns until they return; never flush raw prefixes.
func (s *Streams) Close(abort bool) error {
	defer s.cancel()
	abort = abort || s.failed.Load() || s.Context.Err() != nil
	for _, writer := range []*Writer{s.outWriter, s.errWriter} {
		if writer == nil {
			continue
		}
		if abort {
			writer.Abort()
		} else if err := writer.Close(); err != nil {
			if !errors.Is(err, context.Canceled) && !errors.Is(err, context.DeadlineExceeded) {
				s.failed.Store(true)
			}
			abort = true
		}
	}
	if !abort {
		for _, sink := range s.fileSinks {
			if err := sink.close(); err != nil {
				if !errors.Is(err, context.Canceled) && !errors.Is(err, context.DeadlineExceeded) {
					s.failed.Store(true)
				}
				break
			}
		}
	}
	s.matcher.Destroy()
	if s.failed.Load() {
		return ErrOutput
	}
	return nil
}
